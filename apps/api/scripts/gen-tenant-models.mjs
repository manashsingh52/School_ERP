// Generates src/generated/tenant-models.ts: every Prisma model that has a `schoolId` field.
// The tenant Prisma extension uses this list to auto-scope queries (docs/03-multi-tenancy.md §2).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const schemaPath = fileURLToPath(new URL('../prisma/schema.prisma', import.meta.url));
const outPath = fileURLToPath(new URL('../src/generated/tenant-models.ts', import.meta.url));
const schema = readFileSync(schemaPath, 'utf8');

const tenantModels = [];
const nullableTenantModels = [];
for (const match of schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  const [, name, body] = match;
  const field = body.match(/^\s+schoolId\s+String(\??)\s/m);
  if (!field) continue;
  tenantModels.push(name);
  if (field[1] === '?') nullableTenantModels.push(name);
}

mkdirSync(fileURLToPath(new URL('../src/generated', import.meta.url)), { recursive: true });
writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/gen-tenant-models.mjs — do not edit.
export const TENANT_MODELS: ReadonlySet<string> = new Set(${JSON.stringify(tenantModels, null, 2)});

/** Tenant models whose schoolId may be NULL for platform-level rows (written by the platform client). */
export const NULLABLE_TENANT_MODELS: ReadonlySet<string> = new Set(${JSON.stringify(nullableTenantModels)});
`,
);
console.log(`tenant-models: ${tenantModels.length} tenant models`);
