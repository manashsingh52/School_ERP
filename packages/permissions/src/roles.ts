import type { Permission, PermissionScope } from './catalog.js';

/**
 * Default role templates (docs/04-rbac.md §4). Copied into each school's `roles` table when the
 * school is created; schools can then edit them. Code must never branch on these keys.
 */

export type Grant = readonly [Permission, PermissionScope];

export interface RoleTemplate {
  key: SystemRoleKey;
  name: string;
  description: string;
  grants: readonly Grant[];
}

export type SystemRoleKey = 'school_admin' | 'principal' | 'accountant' | 'teacher' | 'parent';

const all = (...perms: Permission[]): Grant[] => perms.map((p) => [p, 'ALL'] as const);
const scoped = (scope: PermissionScope, ...perms: Permission[]): Grant[] =>
  perms.map((p) => [p, scope] as const);

